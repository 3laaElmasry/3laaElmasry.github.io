// Writes supabase/seed.sql from the content bundled in src/data, so the
// database starts with exactly what the site already shows.
// Usage: node scripts/build-seed.mjs
import { writeFileSync } from 'node:fs';
import { projects } from '../src/data/projects.js';
import { skillGroups } from '../src/data/skills.js';
import { socials } from '../src/data/socials.js';
import { site } from '../src/data/site.js';
import { en } from '../src/i18n/en.js';
import { ar } from '../src/i18n/ar.js';

const text = (value) => `'${String(value).replace(/'/g, "''")}'`;
const json = (value) => (value == null ? 'null' : `${text(JSON.stringify(value))}::jsonb`);

const lines = [
  '-- Generated by scripts/build-seed.mjs. Run after schema.sql.',
  '-- Rows that already exist are left alone, so this never overwrites dashboard edits.',
  '',
];

projects.forEach((p, index) => {
  lines.push(
    `insert into public.projects (id, sort_order, featured, name, url, domain, category, metric, highlight, tags, one_liner, challenge, what_i_built, result, screenshots) values (` +
      [text(p.id), index, p.featured, text(p.name), text(p.url), text(p.domain), json(p.category), json(p.metric),
        json(p.highlight), json(p.tags), json(p.oneLiner), json(p.challenge), json(p.whatIBuilt), json(p.result),
        json(p.screenshots)].join(', ') +
      `) on conflict (id) do nothing;`
  );
});
lines.push('');

skillGroups.forEach((group, index) => {
  const label = { en: en.engineering.skills.groups[group.id], ar: ar.engineering.skills.groups[group.id] };
  lines.push(
    `insert into public.skill_groups (id, sort_order, label, items) values (${text(group.id)}, ${index}, ${json(label)}, ${json(group.items)}) on conflict (id) do nothing;`
  );
});
lines.push('');

socials.forEach((social, index) => {
  lines.push(
    `insert into public.socials (id, sort_order, label, url, icon) values (${text(social.id)}, ${index}, ${text(social.label)}, ${text(social.url)}, ${text(social.id)}) on conflict (id) do nothing;`
  );
});
lines.push('');

const contact = {
  phone: site.phone,
  whatsappNumber: site.whatsappNumber,
  email: site.email,
  whatsappMessage: site.whatsappMessage,
};
lines.push(
  `insert into public.site_settings (key, value) values ('contact', ${json(contact)}) on conflict (key) do nothing;`
);

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), lines.join('\n') + '\n');
console.log(`seed.sql written: ${projects.length} projects, ${skillGroups.length} skill groups, ${socials.length} socials`);
